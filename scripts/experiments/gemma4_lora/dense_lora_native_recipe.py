#!/usr/bin/env python3
"""Schema2 optional native final RMSNorm scale; original dense implementation stays frozen."""

from pathlib import Path
import hashlib
import math
import os
import dense_lora_recipe as dense
from kairyu_bench.wsp.weights import checkpoint as checkpoint_reader
from kairyu_bench.wsp.weights import editor as sparse

ORIGINAL_IMPLEMENTATION = dense.implementation
ORIGINAL_VALIDATE = dense.validated_recipe
ORIGINAL_ENTRIES = dense.entries
NATIVE_TENSOR = "model.language_model.norm.weight"


def implementation():
    result = ORIGINAL_IMPLEMENTATION()
    code = dict(result["implementation_files"])
    code["dense_lora_native_recipe.py"] = dense.digest(
        dense.RUNTIME / "dense_lora_native_recipe.py"
    )
    code["editor.py"] = dense.digest(Path(sparse.__file__))
    code["checkpoint.py"] = dense.digest(Path(checkpoint_reader.__file__))
    result.update(implementation_files=code, implementation_sha256=dense.jsonhash(code))
    return result


def validate(base, spec):
    requested = spec.get("native_edits")
    if not isinstance(requested, list) or len(requested) != 1:
        raise ValueError("native recipe v1 supports exactly one final RMSNorm scale")
    edit = requested[0]
    if (
        set(edit) != {"tensor", "scale"}
        or edit["tensor"] != NATIVE_TENSOR
        or type(edit["scale"]) not in (int, float)
        or not math.isfinite(edit["scale"])
        or edit["scale"] <= 0
    ):
        raise ValueError("explicit finite positive final RMSNorm scale required")
    recipe, mapping, h, off = ORIGINAL_VALIDATE(base, spec)
    name, offset, size, dtype, shape = sparse.tensor_location(base, NATIVE_TENSOR)
    if dtype != "BF16" or len(shape) != 1 or not 1 <= shape[0] <= 1_000_000:
        raise ValueError("native final RMSNorm must be a small BF16 vector")
    native = {
        "tensor": NATIVE_TENSOR,
        "shard": name,
        "offset": offset,
        "size": size,
        "dtype": dtype,
        "shape": shape,
        "entry_kind": "native_sparse_bytes",
    }
    all_mapping = mapping + [native]
    spans = {}
    for item in all_mapping:
        spans.setdefault(item["shard"], []).append(
            (item["offset"], item["offset"] + item["size"])
        )
    for items in spans.values():
        previous = 0
        for lo, hi in sorted(items):
            if lo < previous:
                raise ValueError("native/dense tensor spans overlap")
            previous = hi
    recipe.update(
        mapping_sha256=dense.jsonhash(all_mapping),
        native_edits=requested,
        native_arithmetic="Original BF16 final RMSNorm values times finite scale via existing schema1 encode/decode, FP32 conversion and BF16 ties-to-even once; always original source, never donor output.",
    )
    return recipe, all_mapping, h, off


def entries(base, candidate, recipe, mapping, h, off, write=False):
    regular = [x for x in mapping if x.get("entry_kind") != "native_sparse_bytes"]
    native = [x for x in mapping if x.get("entry_kind") == "native_sparse_bytes"]
    records = ORIGINAL_ENTRIES(base, candidate, recipe, regular, h, off, write)
    if len(native) != 1:
        raise ValueError("missing or repeated final RMSNorm span")
    item = native[0]
    path = candidate / item["shard"]
    source = base / item["shard"]
    if os.path.samefile(path, source) or path.stat().st_nlink != 1:
        raise ValueError("native candidate shard must be private")
    before = sparse.read_at(source, item["offset"], item["size"])
    old = sparse.decode(before, item["dtype"])
    if not all(math.isfinite(x) for x in old):
        raise ValueError("nonfinite original RMSNorm")
    scale = recipe["native_edits"][0]["scale"]
    after = sparse.encode([x * scale for x in old], item["dtype"])
    stored = sparse.decode(after, item["dtype"])
    changed = [i for i, (a, b) in enumerate(zip(old, stored)) if a != b]
    if not changed:
        raise ValueError("native scale vanished after BF16 rounding")
    if sparse.read_at(path, item["offset"], item["size"]) != (
        before if write else after
    ):
        raise ValueError("native original/regenerated bytes differ")
    if write:
        with path.open("r+b", buffering=0) as stream:
            stream.seek(item["offset"])
            if stream.write(after) != len(after):
                raise ValueError("short native write")
            os.fsync(stream.fileno())
        if sparse.read_at(path, item["offset"], item["size"]) != after:
            raise ValueError("native write verification")
    records.append(
        {
            **item,
            "operation": "scale",
            "requested_value": scale,
            "selected_indices": list(range(len(old))),
            "changed_indices": changed,
            "changed_count": len(changed),
            "changed_byte_count": sum(
                before[i : i + 2] != after[i : i + 2] for i in range(0, len(before), 2)
            ),
            "source_tensor_sha256": hashlib.sha256(before).hexdigest(),
            "candidate_tensor_sha256": hashlib.sha256(after).hexdigest(),
            "before_hex": before.hex(),
            "after_hex": after.hex(),
            "source_l2": math.sqrt(sum(x * x for x in old)),
            "delta_l2": math.sqrt(sum((b - a) ** 2 for a, b in zip(old, stored))),
            "maximum_absolute_delta": max(abs(b - a) for a, b in zip(old, stored)),
        }
    )
    return records


dense.implementation = implementation
dense.validated_recipe = validate
dense.entries = entries
if __name__ == "__main__":
    dense.main()
